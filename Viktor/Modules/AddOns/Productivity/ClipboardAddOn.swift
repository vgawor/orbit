import AppKit
import SwiftUI

/// Clipboard history: the last 30 bits of text you copied. Pinned items are saved;
/// everything else lives in memory only, so it's gone when Orbit quits.
@MainActor
@Observable
final class ClipboardAddOn: AddOnModule {
    let id = "addon.clipboard"
    let title = "Clipboard"
    let symbol = "doc.on.clipboard"
    let addOn = AddOnInfo(category: .productivity, tier: .free,
                          summary: "The last 30 things you copied. Pin the ones you want to keep.")

    struct Item: Codable, Identifiable, Equatable {
        var id = UUID()
        var text: String
        /// Seconds since 1970 (stored as a number so it reads back the same way).
        var copied: Double
        var pinned = false
        var date: Date { Date(timeIntervalSince1970: copied) }
    }

    private(set) var items: [Item] = []
    var query = ""
    /// The item that was just copied back, for a short "Copied" tick.
    private(set) var justCopied: UUID?

    private let ctx: AddOnContext
    private let storageKey: String?
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    nonisolated static let limit = 30
    /// Pasteboard types that password managers and other apps use to say "don't keep this".
    nonisolated static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    init(_ ctx: AddOnContext, storageKey: String? = "addon-clipboard") {
        self.ctx = ctx
        self.storageKey = storageKey
        if let storageKey { items = Storage.load([Item].self, from: storageKey) ?? [] }
        if ModuleRegistry.isPreview && storageKey != nil { items = Self.sample }
    }

    // MARK: Pure logic

    /// True when the copied content says it's private or temporary (passwords and the like).
    nonisolated static func shouldSkip(types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) }
    }

    /// Adds `text` on top. A repeat moves the old one up (keeping its pin);
    /// unpinned items beyond `limit` fall off the end. Blank text is ignored.
    nonisolated static func inserting(_ text: String, into items: [Item], at date: Date = .now, limit: Int = limit) -> [Item] {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return items }
        var list = items
        var item = Item(text: text, copied: date.timeIntervalSince1970)
        if let i = list.firstIndex(where: { $0.text == text }) {
            item = list.remove(at: i)
            item.copied = date.timeIntervalSince1970
        }
        list.insert(item, at: 0)
        var kept: [Item] = [], unpinned = 0
        for item in list {
            if !item.pinned { unpinned += 1; if unpinned > limit { continue } }
            kept.append(item)
        }
        return kept
    }

    /// Items matching the search (any case, any accents), pinned first, newest first.
    nonisolated static func filtered(_ items: [Item], query: String) -> [Item] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let hits = q.isEmpty ? items : items.filter { $0.text.range(of: q, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        return hits.filter(\.pinned) + hits.filter { !$0.pinned }
    }

    /// One tidy line for the list: runs of spaces and new lines become single spaces.
    nonisolated static func preview(_ text: String, max: Int = 160) -> String {
        let flat = text.split(whereSeparator: { $0.isWhitespace || $0.isNewline }).joined(separator: " ")
        return flat.count > max ? String(flat.prefix(max)) + "…" : flat
    }

    // MARK: Lifecycle

    func start() {
        lastChange = NSPasteboard.general.changeCount
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        save()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types?.map(\.rawValue) ?? []
        guard !Self.shouldSkip(types: types), let text = pb.string(forType: .string) else { return }
        record(text)
    }

    func record(_ text: String) {
        let wasPinned = items.contains { $0.pinned && $0.text == text }
        items = Self.inserting(text, into: items)
        if wasPinned { save() }
    }

    // MARK: Actions

    var latest: Item? { items.max { $0.copied < $1.copied } }
    var visible: [Item] { Self.filtered(items, query: query) }

    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChange = pb.changeCount
        items = Self.inserting(item.text, into: items)
        justCopied = items.first?.id
        if item.pinned { save() }
        Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.2))
            if self?.justCopied == self?.items.first?.id { self?.justCopied = nil }
        }
    }

    func togglePin(_ item: Item) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        if item.pinned { save() }
    }

    /// Clears everything that isn't pinned.
    func clearUnpinned() { items.removeAll { !$0.pinned } }

    /// Only pinned items are written to disk.
    private func save() {
        guard let storageKey else { return }
        Storage.save(items.filter(\.pinned), to: storageKey)
    }

    // MARK: Views

    var panel: AnyView { AnyView(ClipboardPanel(module: self)) }

    var homeCard: AnyView? {
        AnyView(Button { self.ctx.openPanel(self.id) } label: {
            NotchCard {
                HStack(alignment: .center, spacing: 12) {
                    VStack(alignment: .leading, spacing: 6) {
                        CardLabel("Last copied")
                        if let latest = self.latest {
                            Text(Self.preview(latest.text, max: 120)).font(.system(size: 12.5)).lineLimit(3)
                            Spacer(minLength: 0)
                            Text(ProductivityFormat.ago(latest.date)).font(.system(size: 10.5)).foregroundStyle(Tokens.faint)
                        } else {
                            Text("Copy something and it shows up here.").font(.system(size: 12)).foregroundStyle(Tokens.secondary)
                        }
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                    CatchingOrbit(token: self.latest?.copied, size: 40)
                }
            }
        }.buttonStyle(.plain))
    }

    private static var sample: [Item] {
        let now = Date.now.timeIntervalSince1970
        return [
            Item(text: "https://orbit.app/changelog", copied: now - 40),
            Item(text: "Thanks! I'll send the signed offer over before Friday.", copied: now - 300),
            Item(text: "brew install --cask orbit", copied: now - 900, pinned: true),
            Item(text: "Northwind – kickoff notes\n- budget approved\n- next meeting 14 Nov", copied: now - 3_600),
            Item(text: "#5B9EFF", copied: now - 7_200),
            Item(text: "viktor@example.com", copied: now - 20_000, pinned: true),
        ]
    }
}

// MARK: - Panel

private struct ClipboardPanel: View {
    let module: ClipboardAddOn

    var body: some View {
        @Bindable var module = module
        VStack(alignment: .leading, spacing: 12) {
            HStack(spacing: 10) {
                AddOnHeader(symbol: module.symbol, title: "Clipboard", subtitle: subtitle, tint: ProductivityAddOns.tint)
                CatchingOrbit(token: module.latest?.copied, size: 36)
                    .help("Orbit catches everything you copy")
                ProductivityField(placeholder: "Search", text: $module.query, symbol: "magnifyingglass")
                    .frame(width: 200)
                GlassPillButton(title: "Clear", symbol: "trash") { withAnimation(Tokens.spring) { module.clearUnpinned() } }
                    .help("Clear everything that isn't pinned")
            }
            listCard
        }
    }

    private var subtitle: String {
        let pinned = module.items.filter(\.pinned).count
        return pinned > 0 ? "\(module.items.count) items · \(pinned) pinned" : "Click an item to copy it again"
    }

    private var listCard: some View {
        let list = module.visible
        return NotchScroll {
            VStack(alignment: .leading, spacing: 2) {
                if list.isEmpty {
                    VStack(spacing: 8) {
                        OrbitView(size: 60, mood: module.items.isEmpty ? .normal : .wide, motion: .idle,
                                  gaze: module.items.isEmpty ? CGVector(dx: 0, dy: -0.8) : nil)
                        Text(module.items.isEmpty ? "Nothing copied yet" : "No matches")
                            .font(.system(size: 13, weight: .semibold))
                        Text(module.items.isEmpty ? "Text you copy shows up here. Passwords are skipped." : "Try another word.")
                            .font(.system(size: 11.5)).foregroundStyle(Tokens.secondary)
                    }
                    .frame(maxWidth: .infinity).padding(.top, 70)
                }
                ForEach(list) { ClipboardRow(item: $0, module: module) }
            }
            .padding(6)
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
        .glassCard(24)
    }
}

private struct ClipboardRow: View {
    let item: ClipboardAddOn.Item
    let module: ClipboardAddOn
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 10) {
            Image(systemName: item.pinned ? "pin.fill" : "doc.plaintext")
                .font(.system(size: 11)).foregroundStyle(item.pinned ? Tokens.attention : Tokens.faint)
                .frame(width: 18)
            VStack(alignment: .leading, spacing: 2) {
                Text(ClipboardAddOn.preview(item.text)).font(.system(size: 12.5)).lineLimit(1)
                Text(module.justCopied == item.id ? "Copied" : ProductivityFormat.ago(item.date))
                    .font(.system(size: 10.5))
                    .foregroundStyle(module.justCopied == item.id ? Tokens.live : Tokens.faint)
            }
            Spacer(minLength: 6)
            if hovering {
                ProductivityIconButton(symbol: item.pinned ? "pin.slash" : "pin", help: item.pinned ? "Unpin" : "Pin — kept after restart") {
                    module.togglePin(item)
                }
                ProductivityIconButton(symbol: "xmark", tint: Tokens.faint, help: "Remove") { module.remove(item) }
            }
        }
        .padding(.horizontal, 8).padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(hovering ? Color.white.opacity(0.07) : .clear))
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .onTapGesture { module.copy(item) }
        .help("Click to copy")
        .contextMenu {
            Button("Copy") { module.copy(item) }
            Button(item.pinned ? "Unpin" : "Pin") { module.togglePin(item) }
            Button("Remove", role: .destructive) { module.remove(item) }
        }
    }
}
